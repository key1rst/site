export function translateText(text, locale = "fa") {
  if (locale !== "fa" || typeof text !== "string") return text;
  const normalized = text.trim().replace(/\s+/g, " ");
  if (!normalized) return text;
  const localDigits = (value) => value.replace(/[0-9]/g, (digit) => "۰۱۲۳۴۵۶۷۸۹"[Number(digit)]);
  const listing = normalized.match(/^Showing (\d+(?:–\d+)?) of (\d+) products$/);
  if (listing) return `نمایش ${localDigits(listing[1])} از ${localDigits(listing[2])} محصول`;
  const records = normalized.match(/^Records (\d+)–(\d+)$/);
  if (records) return `رکوردهای ${localDigits(records[1])} تا ${localDigits(records[2])}`;
  const arrow = normalized.match(/\s*[→↗]$/)?.[0] || "";
  const source = arrow ? normalized.slice(0, -arrow.length) : normalized;
  const translated = fa[source] || (
    source.includes("›")
      ? source.split("›").map((part) => fa[part.trim()] || part.trim()).join(" ‹ ")
      : undefined
  );
  if (!translated) return text;
  const leading = text.match(/^\s*/)?.[0] || "";
  const trailing = text.match(/\s*$/)?.[0] || "";
  return `${leading}${translated}${arrow ? " ←" : ""}${trailing}`;
}
